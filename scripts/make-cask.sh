#!/usr/bin/env bash
# Render the Homebrew cask for a release from the template and the built DMG's SHA-256.
#
# Usage: scripts/make-cask.sh VERSION BUILD_DIR
#   e.g. scripts/make-cask.sh 0.2.0 build      (or: make cask VERSION=0.2.0)
# Input:  $BUILD_DIR/Container-Desktop-<version>-arm64.dmg  (the exact file attached to the GitHub release)
# Output: $BUILD_DIR/container-desktop.rb
#
# Env: SHA256 — use this checksum instead of hashing a local DMG (for example the value from a published
#      release's .sha256 asset, when the DMG was built on another Mac).
#
# The checksum must be the one of the published DMG: rebuilding the DMG changes it. If a .sha256 file sits next
# to the DMG (scripts/publish-release.sh writes one), the two must agree. The minimum runtime version in the
# caveats is read from Sources/AppCore/RuntimeSupport.swift, the one place that range is defined.
# This script only writes into BUILD_DIR; it never touches a tap, git or the network.
set -euo pipefail

if [[ $# -ne 2 ]]; then
    echo "usage: $0 VERSION BUILD_DIR" >&2
    exit 64
fi
VERSION="${1#v}"
BUILD_DIR="$2"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
die() { echo "error: $*" >&2; exit 1; }

[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] \
    || die "'$VERSION' is not a stable version (X.Y.Z); pre-releases do not go into the cask"

TEMPLATE="packaging/homebrew/container-desktop.rb.in"
SUPPORT="Sources/AppCore/RuntimeSupport.swift"
[[ -f "$TEMPLATE" ]] || die "missing $TEMPLATE"
[[ -f "$SUPPORT" ]] || die "missing $SUPPORT"

DMG="$BUILD_DIR/Container-Desktop-$VERSION-arm64.dmg"
if [[ -n "${SHA256:-}" ]]; then
    SUM="$SHA256"
else
    [[ -f "$DMG" ]] || die "$DMG not found — build it with 'make dmg VERSION=$VERSION', or pass SHA256=<checksum of the published DMG>"
    SUM="$(shasum -a 256 "$DMG" | awk '{ print $1 }')"
    if [[ -f "$DMG.sha256" ]]; then
        RECORDED="$(awk 'NR == 1 { print $1 }' "$DMG.sha256")"
        [[ "$RECORDED" == "$SUM" ]] \
            || die "$DMG does not match $DMG.sha256 (the DMG was rebuilt after its checksum was written)"
    fi
fi
[[ "$SUM" =~ ^[0-9a-f]{64}$ ]] || die "'$SUM' is not a lowercase SHA-256 checksum"

# `public static let minimum = SemanticVersion(1, 5, 0)` → 1.5.0
MIN_RUNTIME="$(sed -n -E 's/^.*static let minimum = SemanticVersion\(([0-9]+), ([0-9]+), ([0-9]+)\).*$/\1.\2.\3/p' "$SUPPORT")"
[[ "$MIN_RUNTIME" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "could not read the minimum runtime version from $SUPPORT"

mkdir -p "$BUILD_DIR"
OUT="$BUILD_DIR/container-desktop.rb"
# The values are digits, dots and hex only (checked above), so they are safe on sed's replacement side.
sed \
    -e "s|@VERSION@|$VERSION|g" \
    -e "s|@SHA256@|$SUM|g" \
    -e "s|@MIN_RUNTIME@|$MIN_RUNTIME|g" \
    -e '1,2d' \
    "$TEMPLATE" > "$OUT.tmp"
{
    echo "# Homebrew cask for Container Desktop $VERSION. Generated by scripts/make-cask.sh from"
    echo "# packaging/homebrew/container-desktop.rb.in in the app's repository; edit the template, not this file."
    cat "$OUT.tmp"
} > "$OUT"
rm -f "$OUT.tmp"

if grep -q '@[A-Z_0-9]*@' "$OUT"; then
    die "unreplaced placeholder left in $OUT: $(grep -o '@[A-Z_0-9]*@' "$OUT" | sort -u | tr '\n' ' ')"
fi
if command -v ruby > /dev/null 2>&1; then
    RUBY_CHECK="$(ruby -c "$OUT" 2>&1)" || die "$OUT is not valid Ruby: $RUBY_CHECK"
fi

echo "==> rendered $OUT (version $VERSION, sha256 $SUM, runtime >= $MIN_RUNTIME)"
echo "$OUT"
